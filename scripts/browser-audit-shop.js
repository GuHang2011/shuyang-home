async page => {
  const passed = [], errors = [];
  const check = (condition, label) => { if (!condition) throw new Error(label); passed.push(label); };
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 900 });
  const base = new URL(page.url());
  if (!['127.0.0.1', 'localhost'].includes(base.hostname)) throw new Error('Open the isolated local Web preview before running this audit');
  await page.goto(base.origin + '/');
  await page.evaluate(() => sessionStorage.removeItem('shuyang_home_session'));
  await page.reload();
  const failure = route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ code: 503, message: '测试：商品服务暂不可用' }) });
  await page.route('**/api/products?*', failure);
  await page.getByRole('button', { name: '家乡特产', exact: true }).click();
  await page.getByText('测试：商品服务暂不可用', { exact: false }).waitFor();
  check(await page.getByText('家乡好物正在准备中，欢迎常来看看。', { exact: true }).count() === 0, 'load failure is not shown as an empty catalogue');
  await page.unroute('**/api/products?*', failure);
  await page.getByRole('button', { name: '重新加载', exact: true }).click();
  await page.getByRole('heading', { name: '验收特产 · 不销售', exact: true }).waitFor();
  check(await page.getByText('测试：商品服务暂不可用', { exact: false }).count() === 0, 'successful retry clears the error');
  await page.getByRole('textbox', { name: '搜索家乡特产' }).fill('无此商品审计');
  await page.getByText('没有找到符合条件的商品。', { exact: false }).waitFor();
  await page.screenshot({ path: '../output/playwright/audit-web-search.png', fullPage: true });
  await page.getByRole('button', { name: '清除筛选', exact: true }).click();
  await page.getByRole('heading', { name: '验收特产 · 不销售', exact: true }).waitFor();
  await page.getByRole('textbox', { name: '搜索家乡特产' }).fill('  验收特产  ');
  check(await page.getByRole('heading', { name: '验收特产 · 不销售', exact: true }).count() === 1, 'search trims accidental spaces and supports reset');
  await page.getByRole('button', { name: '登录 / 加入', exact: true }).click();
  await page.getByRole('textbox', { name: '手机号 / 管理员账号' }).fill('13800008881');
  await page.getByRole('textbox', { name: '登录密码', exact: true }).fill('CommunityMember2026');
  await page.getByRole('button', { name: '登录，回家看看', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: /验收特产 · 不销售 江苏沭阳/ }).click();
  await page.getByRole('button', { name: '填写订单', exact: true }).click();
  await page.getByRole('combobox', { name: '配送方式', exact: true }).selectOption('pickup');
  await page.getByRole('checkbox').check();
  let writes = 0;
  const countOrder = request => { if (request.url().endsWith('/api/orders') && request.method() === 'POST') writes++; };
  page.on('request', countOrder);
  await page.getByRole('button', { name: '提交订单 · 待人工确认', exact: true }).click();
  await page.getByText('订单已提交，等待卖家人工确认；请勿重复下单。', { exact: true }).waitFor();
  await page.getByRole('button', { name: '取消订单', exact: true }).first().waitFor();
  check(writes === 1, 'order submission creates exactly one request and shows confirmation');
  page.off('request', countOrder);
  const cancel = page.getByRole('button', { name: '取消订单', exact: true }).first();
  await cancel.click();
  const dialog = page.getByRole('dialog', { name: '取消订单', exact: true });
  await dialog.waitFor();
  for (let i = 0; i < 5; i++) await page.keyboard.press('Tab');
  check(await dialog.evaluate(element => element.contains(document.activeElement)), 'order dialog traps keyboard focus');
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'hidden' });
  check(await cancel.evaluate(element => document.activeElement === element), 'Escape closes dialog and restores trigger focus');
  await cancel.click();
  await dialog.getByRole('button', { name: '确认', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  await page.getByText('已取消', { exact: true }).first().waitFor();
  await page.getByText('已取消，无需结算', { exact: true }).first().waitFor();
  passed.push('cancelled unpaid orders no longer ask for settlement');
  passed.push('order cancellation completes in the real isolated backend');
  for (const size of [{ width: 1440, height: 900 }, { width: 768, height: 1024 }, { width: 390, height: 844 }, { width: 360, height: 800 }]) {
    await page.setViewportSize(size);
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `order layout fits ${size.width}px`);
  }
  await page.locator('.toast').waitFor({ state: 'hidden' });
  await page.screenshot({ path: '../output/playwright/audit-web-phone-orders.png', fullPage: true });
  check(errors.length === 0, 'no uncaught browser errors: ' + errors.join('; '));
  return { passed, count: passed.length };
}
