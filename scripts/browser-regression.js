async page => {
  const errors = [];
  const failed = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.url().includes('/api/') && response.status() >= 400) failed.push(response.url() + ' ' + response.status()); });
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.goto('http://127.0.0.1:18888');
  await page.getByRole('button', { name: '我的会员中心', exact: true }).click();
  await page.getByRole('button', { name: '退出登录', exact: true }).click();
  await page.getByRole('button', { name: '登录 / 加入', exact: true }).click();
  await page.getByRole('textbox', { name: '手机号 / 管理员账号' }).fill('admin');
  await page.getByRole('textbox', { name: '登录密码', exact: true }).fill('BrowserAdminChanged2026');
  await page.getByRole('button', { name: '登录，回家看看', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: /管理工作台/ }).click();
  await page.getByRole('button', { name: '互助审核', exact: true }).click();
  await page.getByRole('button', { name: '审核内容', exact: true }).click();
  await page.getByRole('button', { name: '确认审核', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: '家乡与公告', exact: true }).click();
  await page.getByRole('button', { name: '发布公告', exact: true }).click();
  await page.getByRole('textbox', { name: '标题', exact: true }).fill('验收公告 · 欢迎回家');
  await page.getByRole('textbox', { name: '内容', exact: true }).fill('这是一条用于验收的公告，验证家乡消息和公告发布流程。');
  await page.getByRole('button', { name: '保存公告', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: '验收公告 · 欢迎回家', exact: true }).waitFor();
  await page.getByRole('button', { name: '我的会员中心', exact: true }).click();
  await page.getByRole('button', { name: '修改密码', exact: true }).click();
  await page.getByRole('textbox', { name: '原密码', exact: true }).fill('BrowserAdminChanged2026');
  await page.getByRole('textbox', { name: '新密码', exact: true }).fill('BrowserAdminFinal2026');
  await page.getByRole('button', { name: '更新密码', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: '乡情首页', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.content')?.getAttribute('aria-busy') === 'false');
  await page.getByRole('button', { name: /管理工作台/ }).waitFor();
  await page.getByRole('button', { name: '我的会员中心', exact: true }).click();
  await page.getByRole('button', { name: '退出登录', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.content')?.getAttribute('aria-busy') === 'false');
  if (errors.length || failed.length) throw new Error(JSON.stringify({ errors, failed }));
  console.log('Post review, announcement and password/session regression: PASS');
}
